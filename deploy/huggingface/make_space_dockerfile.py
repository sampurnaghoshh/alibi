"""Generate the Hugging Face Space Dockerfile from the repo's root Dockerfile.

The Space repo only needs two small files (this folder's README.md and the generated Dockerfile), so
nothing heavy is uploaded from a slow connection: the Space's builder fetches this public GitHub repo
at one pinned commit and then runs exactly the same build steps as the root Dockerfile.

    python deploy/huggingface/make_space_dockerfile.py                      # refresh the committed copy
    python deploy/huggingface/make_space_dockerfile.py --commit <sha> --out <space folder>/Dockerfile

Pin a commit SHA in the Space: with a branch name, the Space's build cache may keep an older checkout.
tests/test_deploy.py checks that the committed copy is up to date.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
DEFAULT_REPO_URL = "https://github.com/sampurnaghoshh/alibi.git"

SOURCE_STAGE = """# --- 0. the source: this repo's public GitHub copy, at one pinned commit --------------------------
FROM debian:bookworm-slim AS source
RUN apt-get update && apt-get install -y --no-install-recommends git ca-certificates \\
 && rm -rf /var/lib/apt/lists/*
ARG ALIBI_REPO={repo}
ARG ALIBI_COMMIT={commit}
RUN git init -q /src && cd /src && git remote add origin "$ALIBI_REPO" \\
 && git fetch -q --depth 1 origin "$ALIBI_COMMIT" && git checkout -q FETCH_HEAD

"""

HEADER = """# GENERATED by deploy/huggingface/make_space_dockerfile.py from the repo's root Dockerfile. Do not edit.
# Hugging Face Space build: fetches {repo} at ALIBI_COMMIT, then builds exactly like the root Dockerfile.
# Set ALIBI_COMMIT to the commit SHA you want live (and push the Space again to redeploy).

"""

COPY_RE = re.compile(r"^COPY(?P<flags>(?:\s+--\S+)*)\s+(?P<rest>.+)$")


def convert(root_dockerfile: str, commit: str, repo: str) -> str:
    out = [HEADER.format(repo=repo), SOURCE_STAGE.format(repo=repo, commit=commit)]
    for line in root_dockerfile.splitlines():
        m = COPY_RE.match(line)
        if m and "--from=" not in m.group("flags"):
            parts = m.group("rest").split()
            sources, dest = parts[:-1], parts[-1]
            line = f"COPY{m.group('flags')} --from=source " + " ".join(f"/src/{s}" for s in sources) + f" {dest}"
        out.append(line + "\n")
    return "".join(out)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--commit", default="main", help="commit SHA (or branch) the Space builds")
    ap.add_argument("--repo", default=DEFAULT_REPO_URL)
    ap.add_argument("--out", type=Path, default=HERE / "Dockerfile")
    args = ap.parse_args(argv)
    text = convert((REPO / "Dockerfile").read_text(encoding="utf-8"), args.commit, args.repo)
    args.out.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {args.out} (commit {args.commit})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
